def determinar_unidade(nome: str) -> str:
    """Determina a unidade de medida baseada no nome do produto."""
    nome_lower = nome.lower()

    padroes = [
        (r"(\d+\.?\d*)\s*kg\b", "kg"),
        (r"(\d+\.?\d*)\s*g\b", "g"),
        (r"(\d+\.?\d*)\s*l\b", "l"),
        (r"(\d+\.?\d*)\s*ml\b", "ml"),
        (r"\bkg\b", "kg"),
        (r"\bg\b", "g"),
        (r"\bl\b", "l"),
        (r"\bml\b", "ml"),
        (r"\bun\b", "un"),
        (r"\bpct\b", "pct"),
        (r"\bcx\b", "cx"),
        (r"\bcaixa\b", "cx"),
        (r"\bcento\b", "un"),
        (r"(\d+)\s*unidades?\b", "un"),
    ]

    for padrao, unidade in padroes:
        if re.search(padrao, nome_lower):
            return unidade

    # Fallback por tipo
    if any(p in nome_lower for p in ["leite", "refri", "suco", "água", "cerveja", "vinho"]):
        return "l"
    if any(p in nome_lower for p in ["biscoito", "salgadinho", "chocolate", "bombom", "bala"]):
        return "g" if "g" in nome_lower else "un"
    if any(p in nome_lower for p in ["arroz", "feijão", "açúcar", "farinha", "macarrão"]):
        return "kg" if "kg" in nome_lower else "g"

    return "un"


def gerar_nome_limpo(nome_original: str, marca: str | None = None) -> str:
    """
    Gera um nome_limpo simplificado para o produto,
    removendo marca, quantidade e unidades óbvias.
    """
    tokens = nome_original.strip().split()
    resultado = []
    marca_upper = (marca or "").upper()

    for t in tokens:
        t_limpo = t.strip(",").upper()

        # Remove marca
        if marca_upper and marca_upper in t_limpo:
            continue

        # Remove tokens de unidade / quantidade
        if t_limpo in {"KG", "G", "ML", "L", "UN", "PCT", "CX"}:
            continue
        if t_limpo.replace(",", "").replace(".", "").isdigit():
            continue

        resultado.append(t_limpo)

    if not resultado:
        return nome_original.upper()

    # Pega até 3 palavras principais
    return " ".join(resultado[:3])


