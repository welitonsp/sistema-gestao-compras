# Função principal: popular banco
# -----------------------------------------------------------------------------
def popular_banco():
    """Limpa as tabelas e insere os 500 produtos com histórico de preços fictícios."""
    conn = conectar()
    cursor = conn.cursor()

    # Limpar tabelas
    print("🧹 Limpando tabelas existentes (historico_precos, produtos)...")
    cursor.execute("DELETE FROM historico_precos;")
    cursor.execute("DELETE FROM produtos;")
    conn.commit()

    produtos = processar_lista_produtos()
    total_produtos = len(produtos)

    print(f"📦 Processando {total_produtos} produtos...")
    print("=" * 60)

    inseridos = 0
    categorias_processadas: dict[str, int] = {}

    precos_por_categoria = {
        "ALIMENTOS BÁSICOS": (5.0, 50.0),
        "HORTIFRUTI": (2.0, 20.0),
        "LATICÍNIOS": (3.0, 30.0),
        "LIMPEZA": (5.0, 60.0),
        "HIGIENE PESSOAL": (2.0, 40.0),
        "LANCHE": (1.0, 25.0),
        "BEBIDAS": (3.0, 40.0),
        "OUTROS": (2.0, 100.0),
    }

    mercados_ficticios = [
        "ATACADAO DIA A DIA",
        "CARREFOUR",
        "EXTRA",
        "PAO DE ACUCAR",
        "MERCADO LOCAL",
    ]

    data_base = datetime.now()

    for i, (nome_original, categoria_desejada) in enumerate(produtos, start=1):
        try:
            # Gera um "ean" estável a partir do nome
            ean = hashlib.md5(nome_original.encode("utf-8")).hexdigest()[:12]

            marca = extrair_marca(nome_original)
            unidade = determinar_unidade(nome_original)
            nome_limpo = gerar_nome_limpo(nome_original, marca)

            categoria = categoria_desejada.upper()

            # Insere produto
            cursor.execute(
                """
                INSERT INTO produtos (ean, nome_original, nome_limpo, marca, categoria, unidade)
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT (ean) DO NOTHING;
            """,
                (ean, nome_original, nome_limpo, marca, categoria, unidade),
            )

            categorias_processadas[categoria] = categorias_processadas.get(categoria, 0) + 1

            # Preço fictício pela categoria
            preco_min, preco_max = precos_por_categoria.get(categoria, (5.0, 50.0))
            preco = round(random.uniform(preco_min, preco_max), 2)

            # Quantidade fictícia
            if unidade in {"kg", "l"}:
                quantidade = round(random.uniform(0.5, 5.0), 2)
            elif unidade in {"g", "ml"}:
                quantidade = round(random.uniform(100, 1000), 0)
            else:
                quantidade = random.randint(1, 10)

            # Data aleatória nos últimos 30 dias
            dias_atras = random.randint(0, 30)
            data_compra = (data_base - timedelta(days=dias_atras)).strftime("%Y-%m-%d")

            mercado = random.choice(mercados_ficticios)

            cursor.execute(
                """
                INSERT INTO historico_precos (ean, data_compra, mercado, preco_pago, quantidade)
                VALUES (%s, %s, %s, %s, %s);
            """,
                (ean, data_compra, mercado, preco, quantidade),
            )

            inseridos += 1

            if i % 50 == 0:
                print(f"✅ Processados {i}/{total_produtos} produtos...")

        except Exception as e:
            print(
                f"❌ Erro ao processar produto {i}: {nome_original[:50]}... "
                f"- {str(e)[:80]}"
            )
            conn.rollback()

    conn.commit()
    cursor.close()
    conn.close()

    print("\n" + "=" * 60)
    print("📊 RELATÓRIO DE INSERÇÃO")
    print("=" * 60)
    print(f"✅ Total de produtos processados: {total_produtos}")
    print(f"✅ Registros inseridos (historico_precos): {inseridos}")
    print(f"✅ Categorias encontradas: {len(categorias_processadas)}")

    print("\n📈 Distribuição por categoria:")
    for categoria, qtd in sorted(categorias_processadas.items()):
        print(f"  • {categoria:20}: {qtd:3} produtos")

    return inseridos


