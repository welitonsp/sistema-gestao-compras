def conectar():
    """Estabelece conexão com o banco de dados PostgreSQL."""
    try:
        conn = psycopg2.connect(LINK_BANCO)
        return conn
    except Error as e:
        print(f"❌ ERRO ao conectar ao banco de dados: {e}")
        raise


def criar_tabelas_se_nao_existirem():
    """Cria as tabelas necessárias (produtos, historico_precos) se não existirem."""
    conn = conectar()
    cursor = conn.cursor()

    try:
        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS produtos (
                ean           VARCHAR(50) PRIMARY KEY,
                nome_original TEXT NOT NULL,
                nome_limpo    VARCHAR(255) NOT NULL,
                marca         VARCHAR(100),
                categoria     VARCHAR(100) NOT NULL,
                unidade       VARCHAR(20) NOT NULL
            );
        """
        )

        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS historico_precos (
                id           SERIAL PRIMARY KEY,
                ean          VARCHAR(50) REFERENCES produtos(ean),
                data_compra  DATE NOT NULL,
                mercado      VARCHAR(255) NOT NULL,
                preco_pago   NUMERIC(10,2) NOT NULL,
                quantidade   NUMERIC(10,3) NOT NULL
            );
        """
        )

        conn.commit()
        print("✅ Tabelas verificadas/criadas com sucesso")
    except Exception as e:
        print(f"❌ ERRO ao criar tabelas: {e}")
        conn.rollback()
    finally:
        cursor.close()
        conn.close()


